/**
 * THE single source of truth for the app version.
 *
 * It used to be hardcoded in five independent places (here twice, Main.kt's
 * sidebar, HomeScreen's footer and SettingsScreen's About card) and they had
 * already drifted — the About card still claimed 3.6.3 while everything else
 * said 3.6.11. The generateBuildInfo task below emits vpn.BuildInfo from this
 * value, and every UI string reads it, so drift is now impossible.
 */
val appVersion = "3.6.17"

group = "com.multivpn"
version = appVersion

kotlin {
    jvmToolchain(17)
}

/** Generates vpn/BuildInfo.kt so the UI can never hardcode a stale version. */
val generatedSrcDir = layout.buildDirectory.dir("generated/buildinfo")

val generateBuildInfo by tasks.registering {
    val outDir = generatedSrcDir
    val v = appVersion
    inputs.property("version", v)
    outputs.dir(outDir)
    doLast {
        val f = outDir.get().file("vpn/BuildInfo.kt").asFile
        f.parentFile.mkdirs()
        f.writeText(
            """
            package vpn

            /** GENERATED by the Gradle `generateBuildInfo` task - do not edit. */
            object BuildInfo {
                const val VERSION: String = "$v"
                const val ARCH: String = "x86_64"
                /** "v3.6.12 · x86_64" */
                val LABEL: String get() = "v${'$'}VERSION · ${'$'}ARCH"
            }

            """.trimIndent(),
        )
    }
}

sourceSets.main { kotlin.srcDir(generateBuildInfo) }

tasks.test {
