compose.desktop {
    application {
        mainClass = "vpn.MainKt"
        nativeDistributions {
            // AppImage = the portable app folder (plain jpackage, no WiX):
            //   gradlew createDistributable
            //   -> build/compose/binaries/main/app/MultiVPN/MultiVPN.exe
            // Msi/Exe are the installers; they REQUIRE WiX 3.x on the build
            // machine (GitHub's windows-latest image ships it):
            //   gradlew packageMsi packageExe
            //   -> build/compose/binaries/main/{msi,exe}/MultiVPN-<ver>.{msi,exe}
            //
            // All three MUST be declared here. Declaring only AppImage meant
            // the packageMsi/packageExe tasks did not exist at all, so the CI
            // workflow and the README both referenced tasks Gradle rejected
            // with "Task 'packageMsi' not found" — no CI run could ever pass.
            //
            // WARNING: Gradle's plain `build` lifecycle never runs any
            // packaging task - call them explicitly (desktop\build.bat does).
            targetFormats(TargetFormat.AppImage, TargetFormat.Msi, TargetFormat.Exe)
            packageName = "MultiVPN"
            packageVersion = appVersion
            description = "MultiVPN - multi-protocol VPN client"
            vendor = "MultiVPN"
            windows {
                iconFile = project.file("icon\\multivpn-shield-m.ico")
                upgradeUuid = "8e2f7a41-6c3b-4d9e-9f5a-2b7c8d1e4a6f"
                console = false
                menu = true
                shortcut = true
            }
            // Modules the bundled jlink runtime must contain. This list is NOT
            // cosmetic: jpackage builds a minimal runtime from exactly these,
            // and anything missing fails only in the PACKAGED app (never in
            // `gradle run`, which uses the full JDK) — the worst class of bug.
            //
            // Verified with:
            //   jdeps --multi-release 17 --print-module-deps --ignore-missing-deps \
            //     -cp "<all app jars>" multivpn-<ver>.jar
            // which reports: java.base java.desktop java.instrument java.naming
            //                java.net.http java.security.jgss java.sql jdk.unsupported
            //
            //  java.net.http        MSI/subscription/core downloads
            //  jdk.crypto.ec        SSH host keys (sshj), EC TLS
            //  java.security.jgss   sshj's AuthGssApiWithMic — reflection over
            //                       SSHClient's methods threw
            //                       NoClassDefFoundError: org/ietf/jgss/Oid
            //                       without it (reproduced with --limit-modules)
            //  java.naming          BouncyCastle CRL/LDAP cert-store paths
            //  java.sql             BouncyCastle LDAPStoreHelper
            //  java.instrument      kotlinx-coroutines debug AgentPremain
            //  jdk.unsupported      sun.misc.Unsafe (Kotlin/Compose internals)
            modules(
                "java.net.http", "jdk.crypto.ec", "java.security.jgss",
                "java.naming", "java.sql", "java.instrument", "jdk.unsupported",
            )
        }
    }
}

